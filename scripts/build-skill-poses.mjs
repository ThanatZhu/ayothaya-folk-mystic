// Packs the October 2026 per-skill character pose sheets for the game and writes the skill → sheet map.
// node scripts/build-skill-poses.mjs [--force]
// Source: assets/skills-next/poses-2026-10/pose-<skill id>.png (1920×640, 6×2 cells of 320, male row 0, female row 1,
// ground anchor 160,276). The PNGs stay as the masters; the game reads game/{hd,sd}/pose-<id>.webp (1920×640 / 960×320).
// Matching is by the manifest's skill id (never by slot or hotbar position).
import {readFileSync,writeFileSync,mkdirSync,existsSync,statSync} from 'node:fs';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {ROLES} from '../assets/skills-next/catalog.js';
import {BODY_HEIGHT,FRAME_FOOT} from '../character-size.js';
const force=process.argv.includes('--force'),run=promisify(execFile);
const dir=new URL('../assets/skills-next/poses-2026-10/',import.meta.url),path=u=>decodeURIComponent(u.pathname).replace(/^\/([A-Z]:)/,'$1');
const manifest=JSON.parse(readFileSync(new URL('manifest.json',dir),'utf8'));
const actives=new Map(ROLES.flatMap(r=>[...r.base,...r.branches.flatMap(b=>b.active)]).map(s=>[s.id,s]));
const W=1920,H=640,CELL=320;
// Crown = the first row (from the top) with a solid run as wide as a head. A raised spear or a hair
// ribbon is narrower, so it never counts as body height; the manifest's neutralHeightPixels does count it.
function crown(px,gender,frame,minRun){
 const row0=gender==='female'?CELL:0,col0=frame*CELL;
 for(let y=0;y<FRAME_FOOT;y++){let run=0;for(let x=0;x<CELL;x++){if(px[((row0+y)*W+col0+x)*4+3]>100){if(++run>=minRun)return y;}else run=0;}}
 return FRAME_FOOT;
}
const map={},jobs=[],report=[];
for(const s of manifest.sheets){
 const skill=actives.get(s.id);
 if(!skill||skill.classId!==s.classId)throw new Error('No active skill '+s.classId+'/'+s.id);
 if(s.width!==W||s.height!==H||s.columns!==6||s.rows!==2||s.hitFrame!==3||s.genderRows.male!==0||s.genderRows.female!==1||s.frames.some(f=>f.width!==CELL||f.height!==CELL||f.anchor[0]!==160||f.anchor[1]!==FRAME_FOOT||f.x!==f.index*CELL||f.y!==s.genderRows[f.gender]*CELL))throw new Error('Unexpected grid in '+s.filename);
 const file=new URL(s.filename,dir),{stdout:px}=await run('ffmpeg',['-loglevel','error','-i',path(file),'-f','rawvideo','-pix_fmt','rgba','-'],{encoding:'buffer',maxBuffer:W*H*4+1024});
 if(px.length!==W*H*4)throw new Error('Unreadable '+s.filename);
 const scale={},body={};
 for(const g of ['male','female']){
  const minRun=Math.max(8,Math.round(s.neutralHeightPixels[g]*.1));
  // Ready (0) and recover (5) are both planted standing poses; the taller one is the least crouched.
  body[g]=Math.max(...[0,5].map(f=>FRAME_FOOT-crown(px,g,f,minRun)));
  scale[g]=+(BODY_HEIGHT/body[g]).toFixed(4);
 }
 map[s.id]={classId:s.classId,ultimate:!!s.ultimate,scale,air:[...new Set(s.sourceFrames.filter(f=>f.airborne).map(f=>f.index))]};
 report.push([s.id,body.male,s.neutralHeightPixels.male,body.female,s.neutralHeightPixels.female]);
 for(const [tier,w,q] of [['hd',1920,90],['sd',960,88]]){
  const out=new URL('game/'+tier+'/',dir),target=new URL(s.filename.replace(/\.png$/,'.webp'),out);mkdirSync(out,{recursive:true});
  if(!force&&existsSync(target)&&statSync(target).mtimeMs>statSync(file).mtimeMs)continue;
  jobs.push(['-loglevel','error','-y','-i',path(file),'-vf',`scale=${w}:${w/3}:flags=lanczos`,'-c:v','libwebp','-pix_fmt','yuva420p','-quality',String(q),'-compression_level','6',path(target)]);
 }
}
await Promise.all(Array.from({length:6},async()=>{while(jobs.length)await run('ffmpeg',jobs.shift());}));
const missing=[...actives.keys()].filter(id=>!map[id]);
writeFileSync(new URL('pose-map.js',dir),'// Generated by scripts/build-skill-poses.mjs from manifest.json. Do not edit by hand.\n'+
 '// Live skill id → pose sheet game/hd|sd/pose-<id>.webp: 6×2 cells (male row 0, female row 1), ground anchor (160,276) of 320,\n'+
 '// frame 3 = contact. scale = the factor that makes the standing body BODY_HEIGHT px tall, like every other painted frame.\n'+
 'export const POSE_SHEETS='+JSON.stringify(map).replace(/\},"/g,'},\n"')+';\n');
const odd=report.filter(([,bm,nm,bf,nf])=>Math.abs(bm/nm-1)>.04||Math.abs(bf/nf-1)>.04);
console.log('skills',Object.keys(map).length,'missing',missing.join(' ')||'none');
console.log('body height differs from manifest neutral height (>4%):',odd.map(r=>r[0]+' '+r.slice(1).map(Math.round).join('/')).join(', ')||'none');
