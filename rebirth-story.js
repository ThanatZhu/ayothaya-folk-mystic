// Saved state: {v, quest, started}. quest = index of the current rb quest; started = its intro has been met at the NPC.
// The quests' own objectives arrive with their maps, so for now meeting the NPC is the only progress there is.
export function normalizeRebirthStory(state){
 const s=state&&typeof state==='object'&&state.v===REBIRTH_STORY_VERSION?state:{};
 const quest=Number.isInteger(s.quest)?Math.min(Math.max(s.quest,0),REBIRTH_STORY.length):0;
 return {v:REBIRTH_STORY_VERSION,quest,started:quest<REBIRTH_STORY.length&&s.started===true};
}
// Talking to the current quest's NPC on its map starts that quest. Characters that never reborn get nothing.
export function rebirthTalk(state,{npc,mapId}={},rebirth=0){
 const s=normalizeRebirthStory(state),quest=REBIRTH_STORY[s.quest];
 if(rebirth<1||!quest||s.started||quest.npc!==npc||quest.mapId!==mapId)return {state:s,changed:false};
 return {state:{...s,started:true},changed:true};
}
// Intros the player may replay: every quest before the current one, plus the current one once started.
export const rebirthUnlocked=(state,rebirth=0)=>{if(rebirth<1)return [];const s=normalizeRebirthStory(state);return REBIRTH_STORY.slice(0,s.quest+(s.started?1:0));};
export function rebirthScene(id,name=''){
 const index=REBIRTH_STORY.findIndex(q=>q.id===id),quest=REBIRTH_STORY[index];if(!quest)return null;
 return {id:'rebirth:'+id,seenId:'rebirth:'+id,title:quest.title,chapter:chapterName(quest.chapter),name,
  tap:'complete',art:{src:`./assets/story-rebirth/${id}.webp?v=rb1`,panels:3,frames:quest.frames,zoom:.05},captions:[...quest.lines]};
}
// Only at a real NPC conversation, like the chapter-1 scenes: the current quest's NPC on its own map.
export function rebirthSceneForNPCTalk(state,npc,mapId,rebirth=0,name=''){
 if(rebirth<1||!npc)return null;
 const s=normalizeRebirthStory(state),quest=REBIRTH_STORY[s.quest];
 if(!quest||quest.npc!==npc.name||quest.mapId!==mapId)return null;
 return rebirthScene(quest.id,name);
}
