// Packs the October 2026 skill VFX sheets for the game and writes the skill → sheet map.
// node scripts/build-skill-vfx.mjs <folder with manifest.json and the final fx-*.png sheets>
// Matching is by profession + skill name from the manifest title (never by slot or hotbar position).
// Output: assets/skills-next/vfx-2026-10/game/{hd,sd}/<sheet>.webp (1536×768 desktop, 1024×512 mobile)
// and assets/skills-next/vfx-2026-10/vfx-map.js. Existing WebP files are kept unless --force.
import {readFileSync,writeFileSync,mkdirSync,existsSync,statSync} from 'node:fs';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
import {ROLES} from '../assets/skills-next/catalog.js';
import {NOVICE} from '../classes.js';
import {NOVICE_SLOTS} from '../skill-progress.js';
const src=process.argv[2],force=process.argv.includes('--force');
if(!src)throw new Error('usage: node scripts/build-skill-vfx.mjs <vfx folder>');
const manifest=JSON.parse(readFileSync(src+'/manifest.json','utf8'));
const out=new URL('../assets/skills-next/vfx-2026-10/',import.meta.url);
const skills={};
for(const r of ROLES)for(const s of [...r.base,...r.branches.flatMap(b=>b.active)])skills[r.id+'|'+s.name]=s.id;
// Novice skills are not role skills: their live id is novice:<save slot>, found through the Novice name list.
NOVICE_SLOTS.forEach(slot=>{skills['novice|'+NOVICE.names[slot]]='novice:'+slot;});
const map={},unmatched=[],jobs=[];
for(const sheet of manifest.sheets){
 if(sheet.columns!==4||sheet.rows!==2||sheet.width!==2048||sheet.height!==1024||sheet.frames.some((f,i)=>f.x!==i%4*512||f.y!==Math.floor(i/4)*512||f.width!==512||f.height!==512))throw new Error('Unexpected grid in '+sheet.filename);
 const name=sheet.title.split(' · ')[0],id=skills[sheet.classId+'|'+name],key=sheet.filename.replace(/\.png$/,'');
 if(!id){unmatched.push({file:sheet.filename,classId:sheet.classId,name});continue;}
 const entry=map[id]??={name,classId:sheet.classId,ultimate:!!sheet.ultimate};
 entry[sheet.kind==='ground'?'ground':'effect']=key;
 for(const [tier,w,q] of [['hd',1536,78],['sd',1024,76]]){
  const dir=new URL('game/'+tier+'/',out),file=new URL(key+'.webp',dir);mkdirSync(dir,{recursive:true});
  if(!force&&existsSync(file)&&statSync(file).mtimeMs>statSync(src+'/'+sheet.filename).mtimeMs)continue;
  jobs.push(['-loglevel','error','-y','-i',src+'/'+sheet.filename,'-vf',`scale=${w}:${w/2}:flags=lanczos`,'-c:v','libwebp','-pix_fmt','yuva420p','-quality',String(q),'-compression_level','6',decodeURIComponent(file.pathname).replace(/^\/([A-Z]:)/,'$1')]);
 }
}
const run=promisify(execFile);
await Promise.all(Array.from({length:6},async()=>{while(jobs.length)await run('ffmpeg',jobs.shift());}));
const missing=[...Object.values(skills)].filter(id=>!map[id]?.effect);
writeFileSync(new URL('vfx-map.js',out),'// Generated by scripts/build-skill-vfx.mjs from manifest.json. Do not edit by hand.\n'+
 '// Live skill id → sheet keys (game/hd|sd/<key>.webp, 4×2 frames of 512 px in the source, frame 3 = peak).\n'+
 'export const VFX_SHEETS='+JSON.stringify(map,null,0).replace(/\},"/g,'},\n"')+';\n'+
 'export const VFX_UNMATCHED='+JSON.stringify(unmatched)+';\n');
console.log('skills',Object.keys(map).length,'sheets',Object.values(map).reduce((n,e)=>n+!!e.effect+!!e.ground,0),'unmatched',unmatched.map(u=>u.file).join(' ')||'none','skills without sheet',missing.join(' ')||'none');
